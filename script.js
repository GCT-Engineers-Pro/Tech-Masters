document.getElementById("submit").addEventListener("click", function(){
  var s = document.getElementById("subject").value.trim();
  var c = document.getElementById("content").value.trim();
  if (!s || !c){
    fbMsg.className = "msg err";
    fbMsg.textContent = "Enter both a subject and your message, then select Submit.";
    return;
  }
  var url = "mailto:" + TO + "?subject=" + encodeURIComponent(s) + "&body=" + encodeURIComponent(c);
  fbMsg.className = "msg ok";
  fbMsg.textContent = "Your email app is opening. Send the email there to deliver your message.";
  window.location.href = url;
});


function go(route){ location.hash = route; }

function render(){
  var h = location.hash;
  if (h && h.indexOf("#/") !== 0) return false;   /* links like #years or #feedback: leave the menu as it is */
  var p = h.replace(/^#\/?/, "").split("/").filter(Boolean).map(Number);
  var y = p[0], s = p[1], i = p[2];
  if (y >= 1 && y <= 4){
    if (s === 2*y - 1 || s === 2*y){
      if (DATA[s] && DATA[s][i] !== undefined) showFiles(y, s, i);
      else showCategories(y, s);
    } else {
      showSemesters(y);
    }
  } else {
    showYears();
  }
  return true;
}

window.addEventListener("hashchange", function(){
  if (render()){
    var sec = document.getElementById("years");
    if (sec && sec.scrollIntoView) sec.scrollIntoView();
  }
});

render();
