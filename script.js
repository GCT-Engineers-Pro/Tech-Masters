var view = document.getElementById("view");
var crumbs = document.getElementById("crumbs");
var viewTitle = document.getElementById("viewTitle");
var viewSub = document.getElementById("viewSub");
var backBtn = document.getElementById("backBtn");
var backAction = null;
var ORD = ["First", "Second", "Third", "Fourth"];

function getSections(s){ return DATA[s] || []; }

/* Accepts a full Drive link, or just a file ID */
function linkOf(v){
  if (!v) return "";
  v = String(v).trim();
  if (/^https?:\/\//i.test(v)) return v;
  return "https://drive.google.com/uc?export=download&id=" + encodeURIComponent(v);
}

function makeCard(title, text, label, onClick){
  var art = document.createElement("article");
  art.className = "card";
  var h = document.createElement("h3"); h.textContent = title;
  var p = document.createElement("p"); p.textContent = text;
  var b = document.createElement("button");
  b.type = "button"; b.className = "btn btn-primary btn-small"; b.textContent = label;
  b.addEventListener("click", onClick);
  art.appendChild(h); art.appendChild(p); art.appendChild(b);
  return art;
}

function setCrumbs(items){
  crumbs.innerHTML = "";
  items.forEach(function(it, i){
    if (i > 0){
      var sep = document.createElement("span"); sep.className = "sep"; sep.textContent = "›";
      crumbs.appendChild(sep);
    }
    if (it.action){
      var b = document.createElement("button"); b.type = "button"; b.textContent = it.label;
      b.addEventListener("click", it.action);
      crumbs.appendChild(b);
    } else {
      var s = document.createElement("span"); s.className = "here"; s.textContent = it.label;
      crumbs.appendChild(s);
    }
  });
}

function setBack(fn){
  backAction = fn;
  backBtn.style.display = fn ? "inline-block" : "none";
}
backBtn.addEventListener("click", function(){ if (backAction) backAction(); });

/* Level 1: years */
function showYears(){
  setBack(null);
  setCrumbs([{label: "Home"}]);
  viewTitle.textContent = "Year-wise data";
  viewSub.textContent = "Choose your year to see its semesters.";
  view.innerHTML = "";
  var grid = document.createElement("div"); grid.className = "grid";
  YEAR_NAMES.forEach(function(name, i){
    var y = i + 1;
    grid.appendChild(makeCard(name, "Semester " + (2*y - 1) + " and Semester " + (2*y) + ".", "Open " + ORD[i] + " Year", function(){ showSemesters(y); }));
  });
  view.appendChild(grid);
}

/* Level 2: the two semesters of a year */
function showSemesters(y){
  setBack(showYears);
  setCrumbs([{label: "Home", action: showYears}, {label: YEAR_NAMES[y-1]}]);
  viewTitle.textContent = YEAR_NAMES[y-1];
  viewSub.textContent = "Choose a semester.";
  view.innerHTML = "";
  var grid = document.createElement("div"); grid.className = "grid two";
  [2*y - 1, 2*y].forEach(function(s){
    grid.appendChild(makeCard("Semester " + s, "Study materials, CAT and semester questions, lab manuals and data.", "Open Semester " + s, function(){ showCategories(y, s); }));
  });
  view.appendChild(grid);
}

/* Level 3: the sections of a semester (each semester has its own list) */
function showCategories(y, s){
  setBack(function(){ showSemesters(y); });
  setCrumbs([
    {label: "Home", action: showYears},
    {label: YEAR_NAMES[y-1], action: function(){ showSemesters(y); }},
    {label: "Semester " + s}
  ]);
  viewTitle.textContent = "Semester " + s;
  viewSub.textContent = "Choose a section.";
  view.innerHTML = "";
  var grid = document.createElement("div"); grid.className = "grid three";
  getSections(s).forEach(function(sec, idx){
    var n = (sec.files || []).length;
    var info = (sec.text ? sec.text + " · " : "") + n + (n === 1 ? " file" : " files");
    grid.appendChild(makeCard(sec.name, info, "Open files", function(){ showFiles(y, s, idx); }));
  });
  view.appendChild(grid);
}

/* Level 4: the files of one section */
function showFiles(y, s, idx){
  var c = getSections(s)[idx];
  setBack(function(){ showCategories(y, s); });
  setCrumbs([
    {label: "Home", action: showYears},
    {label: YEAR_NAMES[y-1], action: function(){ showSemesters(y); }},
    {label: "Semester " + s, action: function(){ showCategories(y, s); }},
    {label: c.name}
  ]);
  var files = c.files || [];
  viewTitle.textContent = c.name;
  viewSub.textContent = "Semester " + s + " · " + files.length + (files.length === 1 ? " file" : " files");
  view.innerHTML = "";

  var box = document.createElement("div"); box.className = "filebox";
  if (files.length === 0){
    var e = document.createElement("div"); e.className = "empty";
    e.textContent = "No files added yet.";
    box.appendChild(e);
  }
  files.forEach(function(f){
    var row = document.createElement("div"); row.className = "file-row";
    var t = document.createElement("span"); t.className = "file-title"; t.textContent = f[0];
    var url = linkOf(f[1]);
    var action;
    if (url){
      action = document.createElement("a");
      action.className = "btn btn-primary btn-small";
      action.href = url; action.target = "_blank"; action.rel = "noopener noreferrer";
      action.textContent = "Download";
    } else {
      action = document.createElement("span");
      action.className = "btn btn-off btn-small";
      action.textContent = "Link not added";
    }
    row.appendChild(t); row.appendChild(action);
    box.appendChild(row);
  });
  view.appendChild(box);
}

